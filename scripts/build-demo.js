// Builds the browser-only test version:
//   public/demo-data.js           → lets public/index.html work when opened straight from a folder
//   dist/roof-estimator-demo.html → one self-contained file (CSS, JS, data inlined) you can open, email, or host anywhere
// Uses your saved settings (data/config.json) if they exist, otherwise the defaults.
// Run:  npm run build-demo
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const cfgPath = fs.existsSync(path.join(root, 'data/config.json')) ? 'data/config.json' : 'data/config.default.json';
const data = { config: JSON.parse(read(cfgPath)), building: JSON.parse(read('data/mock-building.json')) };
const demoData = `// Generated by scripts/build-demo.js from ${cfgPath} – sample roof + pricing for test mode.\nwindow.RQ_DEMO_DATA = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(root, 'public/demo-data.js'), demoData);

const safe = (js) => js.replace(/<\/script/gi, '<\\/script');
let html = read('public/index.html')
  .replace('<link rel="stylesheet" href="widget.css" />', () => `<style>\n${read('public/widget.css')}\n</style>`)
  .replace('<script src="shared.js"></script>', () => `<script>\n${safe(read('public/shared.js'))}\n</script>`)
  .replace('<script src="demo-data.js"></script>', () => `<script>\nwindow.RQ_FORCE_LOCAL = true;\n${safe(demoData)}</script>`)
  .replace('<script src="widget.js"></script>', () => `<script>\n${safe(read('public/widget.js'))}\n</script>`);
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/roof-estimator-demo.html'), html);
console.log(`Built public/demo-data.js and dist/roof-estimator-demo.html from ${cfgPath}`);
